import path from 'node:path';
import type { Module } from '@shared/schemas/content.js';

/**
 * The repository is public, so anyone can read draft content on GitHub without the app's
 * draft labels (D-17). Every unverified lesson and challenge file therefore starts with a
 * warning, and each content folder has a README saying what in it is unverified.
 * `npm run content:warnings` adds and removes them from `published`; the validator fails
 * when a file is out of step.
 */
export const WARNING_START = 'ltf:unverified-warning:start';
export const WARNING_END = 'ltf:unverified-warning:end';
const MANAGED = 'managed by `npm run content:warnings`, do not edit';

export const WARNING_TITLE = 'UNVERIFIED CONTENT: NOT FOR LEARNING USE';

function warningText(kind: 'lesson' | 'challenge'): string {
  const checked = kind === 'lesson' ? 'checked' : 'flown and checked';
  return (
    `This ${kind} is an unverified draft. It has not been ${checked} in Microsoft Flight ` +
    'Simulator 2024 or against official sources, so its numbers, procedures and steps may ' +
    'be wrong. Do not use it to learn to fly, in the sim or in a real aircraft. Only ' +
    'verified content is published on the Learn to Fly site.'
  );
}

/** Wraps `text` into lines of at most `width` characters. */
function wrap(text: string, width: number): string[] {
  const lines: string[] = [];
  let line = '';
  for (const word of text.split(' ')) {
    if (line && line.length + 1 + word.length > width) {
      lines.push(line);
      line = word;
    } else line = line ? `${line} ${word}` : word;
  }
  if (line) lines.push(line);
  return lines;
}

/** GitHub renders `[!CAUTION]` as a red alert box above the lesson. */
export const MARKDOWN_WARNING = [
  `<!-- ${WARNING_START} (${MANAGED}) -->`,
  '',
  '> [!CAUTION]',
  `> **${WARNING_TITLE}**`,
  '>',
  ...wrap(warningText('lesson'), 88).map((l) => `> ${l}`),
  '',
  `<!-- ${WARNING_END} -->`,
].join('\n');

const RULE = `# ${'='.repeat(78)}`;
export const YAML_WARNING = [
  `# ${WARNING_START} (${MANAGED})`,
  RULE,
  `# ⚠  ${WARNING_TITLE}  ⚠`,
  '#',
  ...wrap(warningText('challenge'), 76).map((l) => `# ${l}`),
  RULE,
  `# ${WARNING_END}`,
].join('\n');

const BLOCK = new RegExp(`^.*${WARNING_START}[\\s\\S]*?${WARNING_END}.*(\\n|$)`, 'm');

export const hasUnverifiedWarning = (source: string): boolean => BLOCK.test(source);

/** Removes the warning, keeping its lines blank so reported line numbers do not move. */
export function blankUnverifiedWarning(source: string): string {
  return source.replace(BLOCK, (block) => block.replace(/[^\n]/g, ''));
}

/** Removes the warning and the blank line that separates it from the content. */
export function removeUnverifiedWarning(source: string): string {
  return source.replace(new RegExp(`${BLOCK.source}\\n?`, 'm'), '');
}

/** Adds the warning right after a lesson's frontmatter. */
export function addLessonWarning(source: string): string {
  if (hasUnverifiedWarning(source)) return source;
  const head = /^---\n[\s\S]*?\n---\n/.exec(source);
  if (!head) return `${MARKDOWN_WARNING}\n\n${source}`;
  const rest = source.slice(head[0].length).replace(/^\n+/, '');
  return `${head[0]}\n${MARKDOWN_WARNING}\n\n${rest}`;
}

/** Adds the warning at the top of a challenge file. */
export function addChallengeWarning(source: string): string {
  if (hasUnverifiedWarning(source)) return source;
  return `${YAML_WARNING}\n${source}`;
}

export interface FolderItem {
  code: string;
  title: string;
  file: string;
  published: boolean;
}

/** README for a content folder: a caution box when anything in it is unverified, then a list. */
export function folderReadme(heading: string, kind: 'lessons' | 'challenges', items: FolderItem[]) {
  const unverified = items.filter((i) => !i.published);
  const lines = [
    `<!-- Generated by \`npm run content:warnings\`. Do not edit. -->`,
    '',
    `# ${heading}`,
    '',
  ];
  if (unverified.length) {
    const scope =
      unverified.length === items.length
        ? `All the ${kind} in this folder are`
        : `The ${kind} marked ⚠ below are`;
    lines.push(
      '> [!CAUTION]',
      `> **${WARNING_TITLE}**`,
      '>',
      ...wrap(
        `${scope} unverified drafts. They have not been checked in Microsoft Flight ` +
          'Simulator 2024 or against official sources, so their numbers, procedures and steps ' +
          'may be wrong. Do not use them to learn to fly, in the sim or in a real aircraft.',
        88,
      ).map((l) => `> ${l}`),
      '',
    );
  } else {
    lines.push(`Every ${kind.slice(0, -1)} in this folder has been verified in the sim.`, '');
  }
  for (const i of items) {
    const status = i.published ? '✅ Verified' : '⚠ **Unverified**';
    lines.push(`- ${status}: [${i.code} ${i.title}](./${path.basename(i.file)})`);
  }
  return `${lines.join('\n')}\n`;
}

export interface ReadmeContent {
  lessons: {
    file: string;
    frontmatter: { code: string; title: string; module: string; order: number; published: boolean };
  }[];
  challenges: { file: string; code: string; title: string; module: string; published: boolean }[];
  modules: Pick<Module, 'slug' | 'code' | 'title'>[];
}

const readmeIn = (file: string) => path.join(path.dirname(file), 'README.md');

/** Every generated README, keyed by its path (relative to the working directory, like `file`). */
export function expectedReadmes({ lessons, challenges, modules }: ReadmeContent) {
  const readmes = new Map<string, string>();
  const moduleBySlug = new Map(modules.map((m) => [m.slug, m]));
  const folders = new Map<string, ReadmeContent['lessons']>();
  for (const l of lessons)
    folders.set(readmeIn(l.file), [...(folders.get(readmeIn(l.file)) ?? []), l]);
  for (const [readme, inFolder] of folders) {
    const m = moduleBySlug.get(inFolder[0]!.frontmatter.module);
    const heading = m ? `${m.code} · ${m.title}` : 'Lessons';
    const items = [...inFolder]
      .sort((a, b) => a.frontmatter.order - b.frontmatter.order)
      .map((l) => ({ ...l.frontmatter, file: l.file }));
    readmes.set(readme, folderReadme(heading, 'lessons', items));
  }
  if (challenges.length) {
    const items = [...challenges].sort((a, b) =>
      a.code.localeCompare(b.code, 'en', { numeric: true }),
    );
    readmes.set(readmeIn(challenges[0]!.file), folderReadme('Challenges', 'challenges', items));
  }
  return readmes;
}

const ROOT_START = 'ltf:verified-content:start';
const ROOT_END = 'ltf:verified-content:end';
const ROOT_BLOCK = new RegExp(`<!-- ${ROOT_START}[\\s\\S]*?${ROOT_END} -->`);

/** The warning at the top of the repository README, listing what is verified. */
export function rootReadmeBlock({ lessons, challenges, modules }: ReadmeContent): string {
  const verifiedLessons = lessons.filter((l) => l.frontmatter.published);
  const verifiedChallenges = challenges.filter((c) => c.published);
  const byCode = (a: { code: string }, b: { code: string }) =>
    a.code.localeCompare(b.code, 'en', { numeric: true });
  const list = modules.flatMap((m) => {
    const codes = [
      ...verifiedLessons
        .map((l) => l.frontmatter)
        .filter((l) => l.module === m.slug)
        .sort(byCode),
      ...verifiedChallenges.filter((c) => c.module === m.slug).sort(byCode),
    ].map((i) => i.code);
    return codes.length ? [`> - ${m.code} · ${m.title}: ${codes.join(', ')}`] : [];
  });
  return [
    `<!-- ${ROOT_START} (generated by \`npm run content:warnings\`, do not edit) -->`,
    '',
    '> [!CAUTION]',
    '> **Most of the content in this repository is unverified and not for learning use.**',
    '>',
    `> Only ${verifiedLessons.length} of ${lessons.length} lessons and ` +
      `${verifiedChallenges.length} of ${challenges.length} challenges have been verified in ` +
      'Microsoft Flight Simulator 2024. Every other lesson and challenge under ' +
      '[`content/`](./content/) is an unverified draft that may be wrong, and starts with a ' +
      "warning saying so. Don't use drafts to learn to fly, in the sim or in a real aircraft.",
    ...(list.length ? ['>', '> Verified so far:', '>', ...list] : []),
    '',
    `<!-- ${ROOT_END} -->`,
  ].join('\n');
}

/** Replaces the generated block in the repository README, or adds it under the title. */
export function syncRootReadme(source: string, block: string): string {
  if (ROOT_BLOCK.test(source)) return source.replace(ROOT_BLOCK, block);
  return source.replace(/^(# .*\n)\n?/, `$1\n${block}\n\n`);
}
